"""
extract_model.py
Offline reimplementation of the embedded feed-forward network used by
the "Mini LLM Sentinel" crackme (sub_140004B30) to score candidate
passwords.

The weights, feature permutation, character-classifier table, and the
XOR-obfuscated prefix/suffix constants are read directly out of the
target binary's .rdata section (located by VA -> file-offset
translation), so this reproduces the exact same decision the live
binary makes without needing a debugger attached.
"""

import math
import struct
from pathlib import Path

BIN = Path("crackme03.exe")

VA_CLASS = 0x14006C540     # 256-entry character-classifier table
VA_PREFIX = 0x14006C713    # 3-byte prefix constant
VA_WEIGHTS = 0x14006C720   # network weights

WEIGHT_SEED = 0xEB78774D
PERM_SEED = 0xB07EC09E


def xorshift32(x: int) -> int:
    x &= 0xFFFFFFFF
    x ^= (x << 13) & 0xFFFFFFFF
    x ^= x >> 17
    x ^= (x << 5) & 0xFFFFFFFF
    return x & 0xFFFFFFFF


def pe_sections(data: bytes) -> list[tuple[int, int, int, int]]:
    e_lfanew = struct.unpack_from("<I", data, 0x3C)[0]
    coff = e_lfanew + 4
    n_sections = struct.unpack_from("<H", data, coff + 2)[0]
    opt_size = struct.unpack_from("<H", data, coff + 16)[0]
    section_table_off = coff + 20 + opt_size

    sections = []
    for i in range(n_sections):
        o = section_table_off + i * 40
        vsize, vaddr, rsize, raw_off = struct.unpack_from("<IIII", data, o + 8)
        sections.append((vaddr, vsize, raw_off, rsize))
    return sections


def va_to_offset(va: int, sections) -> int:
    rva = va - 0x140000000
    for section_va, vsize, raw_off, rsize in sections:
        if section_va <= rva < section_va + max(vsize, rsize):
            return raw_off + (rva - section_va)
    raise ValueError(f"VA not found in any section: {va:#x}")


class SentinelModel:
    """Reconstructed 6-8-1 feed-forward classifier used for password scoring."""

    def __init__(self, image: bytes):
        sections = pe_sections(image)
        offset = lambda va: va_to_offset(va, sections)

        # Character-classifier table: byte-XOR'd against a linear keystream
        raw_table = image[offset(VA_CLASS): offset(VA_CLASS) + 256]
        self.classifier = bytes(
            ((i * 51 + 0x5B) & 0xFF) ^ raw_table[i] for i in range(256)
        )

        # 3-byte prefix constant, XOR'd against a per-index affine keystream
        prefix_ct = image[offset(VA_PREFIX): offset(VA_PREFIX) + 3]
        base_key = (0 - 105) & 0xFF
        self.prefix = bytes(
            prefix_ct[i] ^ ((base_key + 65 * i) & 0xFF) for i in range(3)
        )

        # 1-byte suffix constant, same base key XOR'd with a fixed value
        self.suffix = base_key ^ 0xB6

        # 65 float32 weights, each XOR'd against a running xorshift32 stream
        weights_ct = image[offset(VA_WEIGHTS): offset(VA_WEIGHTS) + 260]
        seed = WEIGHT_SEED
        raw_words = []
        for i in range(65):
            seed = xorshift32(seed)
            raw_words.append(seed ^ struct.unpack_from("<I", weights_ct, i * 4)[0])
        weights = [struct.unpack("<f", struct.pack("<I", w))[0] for w in raw_words]

        self.hidden_weights = [weights[i * 6:(i + 1) * 6] for i in range(8)]  # 8x6
        self.hidden_bias = weights[48:56]                                    # 8
        self.output_weights = weights[56:64]                                 # 8
        self.output_bias = weights[64]

        # Feature permutation, generated by a Fisher-Yates-style shuffle
        # driven by the same xorshift32 PRNG
        perm = bytearray(range(6))
        seed = PERM_SEED
        ptr, remaining = 0, 5
        while True:
            ptr -= 1
            seed = xorshift32(seed)
            idx = seed % remaining
            perm[ptr + 5], perm[idx] = perm[idx], perm[ptr + 5]
            remaining -= 1
            if remaining == 1:
                break
        self.permutation = list(perm)

    def score(self, password: str) -> dict:
        data = password.encode("latin1")
        length = len(data)
        unique_count = len(set(data))

        class_bit0 = class_bit1 = class_bit2 = 0
        class_bit3_all = 1
        byte_sum = 0

        for byte in data:
            cls = self.classifier[byte]
            byte_sum += byte
            class_bit0 += cls & 1
            class_bit1 += (cls >> 1) & 1
            class_bit2 += (cls >> 2) & 1
            class_bit3_all &= (cls >> 3) & 1

        prefix_ok = length >= 3 and data[:3] == self.prefix
        suffix_ok = length >= 1 and data[-1] == self.suffix
        gate = int(bool(class_bit3_all and prefix_ok and suffix_ok))

        sum8 = byte_sum & 0xFF
        distance = abs(sum8 - 101)
        checksum_score = 0.0 if distance > 128 else max(0.0, 1.0 - distance * 0.015625)

        raw_features = [
            float(gate),
            checksum_score,
            1.0 if class_bit0 > 3 else 0.0,
            unique_count * 0.0625,
            class_bit1 * 0.0625,
            class_bit2 * 0.0625,
        ]

        features = [0.0] * 6
        for i, value in enumerate(raw_features):
            features[self.permutation[i]] = value

        hidden = [
            math.tanh(
                self.hidden_bias[i]
                + sum(self.hidden_weights[i][j] * features[j] for j in range(6))
            )
            for i in range(8)
        ]

        logit = self.output_bias + sum(
            self.output_weights[i] * hidden[i] for i in range(8)
        )
        sigmoid = 1.0 / (1.0 + math.exp(-logit))

        return {
            "accepted": length == 16 and sigmoid >= 0.5,
            "sigmoid": sigmoid,
            "sum8": sum8,
        }


def main():
    if not BIN.is_file():
        print(f"Binary not found: {BIN}")
        return

    model = SentinelModel(BIN.read_bytes())

    candidate = "AI-99|~?0=PM;g6!"
    result = model.score(candidate)

    print(f"[*] Testing candidate: {candidate}")
    print(f"[+] Accepted:  {result['accepted']}")
    print(f"[+] Sigmoid:   {result['sigmoid']:.4f}")
    print(f"[+] Checksum:  {result['sum8']} (target: 101)")

    if result["accepted"]:
        print("\n[+] ACCESS GRANTED - password confirmed offline.")
    else:
        print("\n[-] Candidate rejected by the model.")


if __name__ == "__main__":
    main()
